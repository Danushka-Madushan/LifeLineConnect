CREATE TABLE STAFF_MEMBER (
    STAFF_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID              NUMBER,
    FULL_NAME            VARCHAR2(200 CHAR) NOT NULL,
    POSITION_TITLE       VARCHAR2(150 CHAR),
    PHONE                VARCHAR2(30 CHAR),
    EMAIL                VARCHAR2(255 CHAR),
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_STAFF_MEMBER PRIMARY KEY (STAFF_ID),
    CONSTRAINT UQ_STAFF_USER UNIQUE (USER_ID),
    CONSTRAINT CK_STAFF_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT FK_STAFF_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID)
);

CREATE TABLE BANK_STAFF_ASSIGNMENT (
    BANK_STAFF_ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STAFF_ID             NUMBER NOT NULL,
    BLOOD_BANK_ID        NUMBER NOT NULL,
    ASSIGNED_FROM        DATE NOT NULL,
    ASSIGNED_TO          DATE,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_BANK_STAFF_ASSIGNMENT PRIMARY KEY (BANK_STAFF_ASSIGNMENT_ID),
    CONSTRAINT CK_BANK_STAFF_DATES CHECK (ASSIGNED_TO IS NULL OR ASSIGNED_TO >= ASSIGNED_FROM),
    CONSTRAINT CK_BANK_STAFF_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT FK_BANK_STAFF_STAFF FOREIGN KEY (STAFF_ID) REFERENCES STAFF_MEMBER(STAFF_ID),
    CONSTRAINT FK_BANK_STAFF_BANK FOREIGN KEY (BLOOD_BANK_ID) REFERENCES BLOOD_BANK(BLOOD_BANK_ID)
);

CREATE TABLE COMMITTEE_STAFF_ASSIGNMENT (
    COMMITTEE_STAFF_ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STAFF_ID             NUMBER NOT NULL,
    COMMITTEE_ID         NUMBER NOT NULL,
    ASSIGNED_FROM        DATE NOT NULL,
    ASSIGNED_TO          DATE,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_COMMITTEE_STAFF_ASSIGNMENT PRIMARY KEY (COMMITTEE_STAFF_ASSIGNMENT_ID),
    CONSTRAINT CK_COMMITTEE_STAFF_DATES CHECK (ASSIGNED_TO IS NULL OR ASSIGNED_TO >= ASSIGNED_FROM),
    CONSTRAINT CK_COMMITTEE_STAFF_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT FK_COMMITTEE_STAFF_STAFF FOREIGN KEY (STAFF_ID) REFERENCES STAFF_MEMBER(STAFF_ID),
    CONSTRAINT FK_COMMITTEE_STAFF_COMMITTEE FOREIGN KEY (COMMITTEE_ID)
        REFERENCES ORGANIZING_COMMITTEE(COMMITTEE_ID)
);

CREATE TABLE CAMP_STAFF_ASSIGNMENT (
    CAMP_STAFF_ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CAMP_ID              NUMBER NOT NULL,
    STAFF_ID             NUMBER NOT NULL,
    ASSIGNMENT_ROLE      VARCHAR2(100 CHAR),
    ASSIGNED_FROM        TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ASSIGNED_TO          TIMESTAMP WITH LOCAL TIME ZONE,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_CAMP_STAFF_ASSIGNMENT PRIMARY KEY (CAMP_STAFF_ASSIGNMENT_ID),
    CONSTRAINT CK_CAMP_STAFF_DATES CHECK (
        ASSIGNED_TO IS NULL OR ASSIGNED_TO >= ASSIGNED_FROM
    ),
    CONSTRAINT CK_CAMP_STAFF_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT FK_CAMP_STAFF_CAMP FOREIGN KEY (CAMP_ID) REFERENCES DONATION_CAMP(CAMP_ID),
    CONSTRAINT FK_CAMP_STAFF_STAFF FOREIGN KEY (STAFF_ID) REFERENCES STAFF_MEMBER(STAFF_ID)
);
