-- 4. Camp donor registration / attendance
-- Depends on: 02_donor.sql, 03_venues_and_camps.sql

CREATE TABLE CAMP_REGISTRATION (
    REGISTRATION_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CAMP_ID              NUMBER NOT NULL,
    DONOR_ID             NUMBER NOT NULL,
    REGISTERED_AT        TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    REGISTRATION_STATUS  VARCHAR2(20 CHAR) DEFAULT 'REGISTERED' NOT NULL,
    ATTENDANCE_STATUS    VARCHAR2(20 CHAR) DEFAULT 'EXPECTED' NOT NULL,
    CHECK_IN_AT          TIMESTAMP WITH LOCAL TIME ZONE,
    CHECK_OUT_AT         TIMESTAMP WITH LOCAL TIME ZONE,

    CONSTRAINT PK_CAMP_REGISTRATION PRIMARY KEY (REGISTRATION_ID),
    CONSTRAINT UQ_CAMP_DONOR_REGISTRATION UNIQUE (CAMP_ID, DONOR_ID),
    CONSTRAINT CK_CAMP_REG_STATUS CHECK (
        REGISTRATION_STATUS IN ('REGISTERED', 'CANCELLED', 'WAITLISTED', 'CLOSED')
    ),
    CONSTRAINT CK_CAMP_ATTENDANCE_STATUS CHECK (
        ATTENDANCE_STATUS IN ('EXPECTED', 'CHECKED_IN', 'NO_SHOW', 'COMPLETED')
    ),
    CONSTRAINT FK_CAMP_REG_CAMP FOREIGN KEY (CAMP_ID)
        REFERENCES DONATION_CAMP(CAMP_ID),
    CONSTRAINT FK_CAMP_REG_DONOR FOREIGN KEY (DONOR_ID)
        REFERENCES DONOR(DONOR_ID)
);
