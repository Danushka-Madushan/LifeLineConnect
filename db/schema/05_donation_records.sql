-- 5. Donation records
-- Depends on: 04_camp_registration.sql, 03_venues_and_camps.sql, 02_donor.sql

CREATE TABLE DONATION_RECORD (
    DONATION_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REGISTRATION_ID      NUMBER NOT NULL,
    CAMP_ID              NUMBER NOT NULL,
    DONOR_ID             NUMBER NOT NULL,
    DONATION_DATE        DATE NOT NULL,
    BLOOD_GROUP          VARCHAR2(3 CHAR) NOT NULL,
    UNITS_COLLECTED      NUMBER(4,1) DEFAULT 1 NOT NULL,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    NOTES                CLOB,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    SUBMITTED_AT         TIMESTAMP WITH LOCAL TIME ZONE,

    CONSTRAINT PK_DONATION_RECORD PRIMARY KEY (DONATION_ID),
    CONSTRAINT CK_DONATION_BLOOD_GROUP CHECK (
        BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    CONSTRAINT CK_DONATION_UNITS CHECK (UNITS_COLLECTED > 0),
    CONSTRAINT CK_DONATION_STATUS CHECK (
        STATUS IN ('DRAFT', 'SUBMITTED', 'CANCELLED')
    ),
    CONSTRAINT FK_DONATION_REGISTRATION FOREIGN KEY (REGISTRATION_ID)
        REFERENCES CAMP_REGISTRATION(REGISTRATION_ID),
    CONSTRAINT FK_DONATION_CAMP FOREIGN KEY (CAMP_ID)
        REFERENCES DONATION_CAMP(CAMP_ID),
    CONSTRAINT FK_DONATION_DONOR FOREIGN KEY (DONOR_ID)
        REFERENCES DONOR(DONOR_ID)
);
