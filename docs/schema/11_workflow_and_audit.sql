-- 11. Workflow / audit history
-- Depends on: 01_reference_identity.sql

CREATE TABLE ENTITY_STATUS_HISTORY (
    STATUS_HISTORY_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ENTITY_TYPE         VARCHAR2(50 CHAR) NOT NULL,
    ENTITY_ID           NUMBER NOT NULL,
    FROM_STATUS         VARCHAR2(50 CHAR),
    TO_STATUS           VARCHAR2(50 CHAR) NOT NULL,
    CHANGED_BY_USER_ID  NUMBER,
    REASON_CODE         VARCHAR2(100 CHAR),
    REASON_TEXT         VARCHAR2(1000 CHAR),
    CHANGED_AT          TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_ENTITY_STATUS_HISTORY PRIMARY KEY (STATUS_HISTORY_ID),
    CONSTRAINT FK_STATUS_HISTORY_USER FOREIGN KEY (CHANGED_BY_USER_ID)
        REFERENCES APP_USER(USER_ID)
);

CREATE TABLE AUDIT_LOG (
    AUDIT_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ACTOR_USER_ID        NUMBER,
    ACTOR_ROLE_CODE      VARCHAR2(30 CHAR),
    ACTION_CODE          VARCHAR2(100 CHAR) NOT NULL,
    ENTITY_TYPE          VARCHAR2(50 CHAR),
    ENTITY_ID            NUMBER,
    RESULT_CODE          VARCHAR2(30 CHAR),
    DETAILS               CLOB,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (AUDIT_ID),
    CONSTRAINT FK_AUDIT_LOG_USER FOREIGN KEY (ACTOR_USER_ID)
        REFERENCES APP_USER(USER_ID),
    CONSTRAINT CK_AUDIT_ROLE CHECK (
        ACTOR_ROLE_CODE IS NULL OR ACTOR_ROLE_CODE IN (
            'DONOR', 'BLOOD_BANK', 'ORGANIZING_COMMITTEE', 'WEBMASTER'
        )
    )
);
