-- 7. Donation transfer to blood bank
-- Depends on: 03_venues_and_camps.sql, 05_donation_records.sql

CREATE TABLE DONATION_TRANSFER (
    TRANSFER_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CAMP_ID              NUMBER NOT NULL,
    COMMITTEE_ID         NUMBER NOT NULL,
    BLOOD_BANK_ID        NUMBER NOT NULL,
    TRANSFER_CODE        VARCHAR2(40 CHAR) NOT NULL,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'PREPARED' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    DISPATCHED_AT        TIMESTAMP WITH LOCAL TIME ZONE,
    RECEIVED_AT          TIMESTAMP WITH LOCAL TIME ZONE,
    RECEIVED_UNIT_COUNT  NUMBER(8,1),
    NOTES                CLOB,

    CONSTRAINT PK_DONATION_TRANSFER PRIMARY KEY (TRANSFER_ID),
    CONSTRAINT UQ_DONATION_TRANSFER_CODE UNIQUE (TRANSFER_CODE),
    CONSTRAINT CK_TRANSFER_STATUS CHECK (
        STATUS IN ('PREPARED', 'DISPATCHED', 'IN_TRANSIT', 'RECEIVED', 'CANCELLED')
    ),
    CONSTRAINT CK_TRANSFER_RECEIVED_COUNT CHECK (
        RECEIVED_UNIT_COUNT IS NULL OR RECEIVED_UNIT_COUNT >= 0
    ),
    CONSTRAINT FK_TRANSFER_CAMP FOREIGN KEY (CAMP_ID) REFERENCES DONATION_CAMP(CAMP_ID),
    CONSTRAINT FK_TRANSFER_COMMITTEE FOREIGN KEY (COMMITTEE_ID)
        REFERENCES ORGANIZING_COMMITTEE(COMMITTEE_ID),
    CONSTRAINT FK_TRANSFER_BANK FOREIGN KEY (BLOOD_BANK_ID)
        REFERENCES BLOOD_BANK(BLOOD_BANK_ID)
);

CREATE TABLE DONATION_TRANSFER_ITEM (
    TRANSFER_ITEM_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TRANSFER_ID          NUMBER NOT NULL,
    DONATION_ID          NUMBER NOT NULL,
    UNITS_TRANSFERRED    NUMBER(4,1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_DONATION_TRANSFER_ITEM PRIMARY KEY (TRANSFER_ITEM_ID),
    CONSTRAINT UQ_TRANSFER_DONATION UNIQUE (TRANSFER_ID, DONATION_ID),
    CONSTRAINT CK_TRANSFER_ITEM_UNITS CHECK (UNITS_TRANSFERRED > 0),
    CONSTRAINT FK_TRANSFER_ITEM_TRANSFER FOREIGN KEY (TRANSFER_ID)
        REFERENCES DONATION_TRANSFER(TRANSFER_ID),
    CONSTRAINT FK_TRANSFER_ITEM_DONATION FOREIGN KEY (DONATION_ID)
        REFERENCES DONATION_RECORD(DONATION_ID)
);
