-- Depends on: 01_reference_identity.sql

CREATE TABLE DONOR (
    DONOR_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID              NUMBER NOT NULL,
    FULL_NAME            VARCHAR2(200 CHAR) NOT NULL,
    NIC                  VARCHAR2(30 CHAR) NOT NULL,
    DATE_OF_BIRTH        DATE NOT NULL,
    GENDER               VARCHAR2(20 CHAR),
    BLOOD_GROUP          VARCHAR2(3 CHAR),
    PHONE                VARCHAR2(30 CHAR),
    EMAIL                VARCHAR2(255 CHAR),
    ADDRESS              VARCHAR2(500 CHAR),
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_DONOR PRIMARY KEY (DONOR_ID),
    CONSTRAINT UQ_DONOR_USER UNIQUE (USER_ID),
    CONSTRAINT UQ_DONOR_NIC UNIQUE (NIC),
    CONSTRAINT CK_DONOR_BLOOD_GROUP CHECK (
        BLOOD_GROUP IS NULL OR BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    CONSTRAINT CK_DONOR_GENDER CHECK (
        GENDER IS NULL OR GENDER IN ('MALE', 'FEMALE', 'OTHER', 'PREFER_NOT_TO_SAY')
    ),
    CONSTRAINT CK_DONOR_STATUS CHECK (
        STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')
    ),
    CONSTRAINT FK_DONOR_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID)
);

ALTER TABLE USER_ROLE_LINK
    ADD CONSTRAINT FK_USER_ROLE_DONOR FOREIGN KEY (DONOR_ID) REFERENCES DONOR(DONOR_ID);

ALTER TABLE DONOR ADD MEDICAL_CHECK_STATUS VARCHAR2(20);
