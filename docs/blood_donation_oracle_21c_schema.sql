CREATE TABLE BLOOD_UNIT (
    BLOOD_UNIT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BLOOD_BANK_ID        NUMBER NOT NULL,
    DONATION_ID          NUMBER NOT NULL,
    TRANSFER_ID          NUMBER NOT NULL,
    UNIT_CODE            VARCHAR2(50 CHAR) NOT NULL,
    BLOOD_GROUP          VARCHAR2(3 CHAR) NOT NULL,
    COLLECTION_DATE      DATE NOT NULL,
    RECEIVED_DATE        DATE,
    EXPIRY_DATE          DATE NOT NULL,
    STATUS               VARCHAR2(25 CHAR) DEFAULT 'AVAILABLE' NOT NULL,
    STORAGE_LOCATION     VARCHAR2(150 CHAR),
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_BLOOD_UNIT PRIMARY KEY (BLOOD_UNIT_ID),
    CONSTRAINT UQ_BLOOD_UNIT_CODE UNIQUE (UNIT_CODE),
    CONSTRAINT CK_BLOOD_UNIT_GROUP CHECK (
        BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    CONSTRAINT CK_BLOOD_UNIT_DATES CHECK (EXPIRY_DATE > COLLECTION_DATE),
    CONSTRAINT CK_BLOOD_UNIT_STATUS CHECK (
        STATUS IN (
            'AVAILABLE',
            'RESERVED',
            'ALLOCATED',
            'ISSUED',
            'EXPIRED',
            'UNAVAILABLE'
        )
    ),
    CONSTRAINT FK_BLOOD_UNIT_BANK FOREIGN KEY (BLOOD_BANK_ID)
        REFERENCES BLOOD_BANK(BLOOD_BANK_ID),
    CONSTRAINT FK_BLOOD_UNIT_DONATION FOREIGN KEY (DONATION_ID)
        REFERENCES DONATION_RECORD(DONATION_ID),
    CONSTRAINT FK_BLOOD_UNIT_TRANSFER FOREIGN KEY (TRANSFER_ID)
        REFERENCES DONATION_TRANSFER(TRANSFER_ID)
);

