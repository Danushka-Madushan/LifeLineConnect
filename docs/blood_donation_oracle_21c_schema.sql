-- ----------------------------------------------------------------
-- 1. Reference / identity tables
-- ----------------------------------------------------------------

CREATE TABLE APP_USER (
    USER_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USERNAME             VARCHAR2(100 CHAR) NOT NULL,
    EMAIL                VARCHAR2(255 CHAR),
    PASSWORD_HASH        VARCHAR2(500 CHAR) NOT NULL,
    ACCOUNT_STATUS       VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_LOGIN_AT        TIMESTAMP WITH LOCAL TIME ZONE,

    CONSTRAINT PK_APP_USER PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_APP_USER_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_APP_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_APP_USER_STATUS CHECK (
        ACCOUNT_STATUS IN ('ACTIVE', 'INACTIVE', 'LOCKED', 'SUSPENDED', 'DISABLED')
    )
);

CREATE TABLE BLOOD_BANK (
    BLOOD_BANK_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BANK_CODE            VARCHAR2(30 CHAR) NOT NULL,
    BANK_NAME            VARCHAR2(200 CHAR) NOT NULL,
    PHONE                VARCHAR2(30 CHAR),
    EMAIL                VARCHAR2(255 CHAR),
    ADDRESS              VARCHAR2(500 CHAR),
    LATITUDE             NUMBER(9,6),
    LONGITUDE            NUMBER(9,6),
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_BLOOD_BANK PRIMARY KEY (BLOOD_BANK_ID),
    CONSTRAINT UQ_BLOOD_BANK_CODE UNIQUE (BANK_CODE),
    CONSTRAINT CK_BLOOD_BANK_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_BLOOD_BANK_LAT CHECK (LATITUDE IS NULL OR LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_BLOOD_BANK_LON CHECK (LONGITUDE IS NULL OR LONGITUDE BETWEEN -180 AND 180)
);

CREATE TABLE ORGANIZING_COMMITTEE (
    COMMITTEE_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COMMITTEE_CODE       VARCHAR2(30 CHAR) NOT NULL,
    COMMITTEE_NAME       VARCHAR2(200 CHAR) NOT NULL,
    PHONE                VARCHAR2(30 CHAR),
    EMAIL                VARCHAR2(255 CHAR),
    ADDRESS              VARCHAR2(500 CHAR),
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_ORGANIZING_COMMITTEE PRIMARY KEY (COMMITTEE_ID),
    CONSTRAINT UQ_COMMITTEE_CODE UNIQUE (COMMITTEE_CODE),
    CONSTRAINT CK_COMMITTEE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE USER_ROLE_LINK (
    USER_ROLE_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID              NUMBER NOT NULL,
    ROLE_CODE            VARCHAR2(30 CHAR) NOT NULL,
    DONOR_ID             NUMBER,
    BLOOD_BANK_ID        NUMBER,
    COMMITTEE_ID         NUMBER,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_USER_ROLE_LINK PRIMARY KEY (USER_ROLE_ID),
    CONSTRAINT UQ_USER_ROLE_LINK_USER UNIQUE (USER_ID),
    CONSTRAINT CK_USER_ROLE_LINK_ROLE CHECK (
        ROLE_CODE IN ('DONOR', 'BLOOD_BANK', 'ORGANIZING_COMMITTEE', 'WEBMASTER')
    ),
    CONSTRAINT CK_USER_ROLE_LINK_ENTITY CHECK (
        (ROLE_CODE = 'DONOR'
            AND DONOR_ID IS NOT NULL
            AND BLOOD_BANK_ID IS NULL
            AND COMMITTEE_ID IS NULL)
        OR
        (ROLE_CODE = 'BLOOD_BANK'
            AND DONOR_ID IS NULL
            AND BLOOD_BANK_ID IS NOT NULL
            AND COMMITTEE_ID IS NULL)
        OR
        (ROLE_CODE = 'ORGANIZING_COMMITTEE'
            AND DONOR_ID IS NULL
            AND BLOOD_BANK_ID IS NULL
            AND COMMITTEE_ID IS NOT NULL)
        OR
        (ROLE_CODE = 'WEBMASTER'
            AND DONOR_ID IS NULL
            AND BLOOD_BANK_ID IS NULL
            AND COMMITTEE_ID IS NULL)
    ),
    CONSTRAINT FK_USER_ROLE_USER FOREIGN KEY (USER_ID) REFERENCES APP_USER(USER_ID),
    CONSTRAINT FK_USER_ROLE_BANK FOREIGN KEY (BLOOD_BANK_ID) REFERENCES BLOOD_BANK(BLOOD_BANK_ID),
    CONSTRAINT FK_USER_ROLE_COMMITTEE FOREIGN KEY (COMMITTEE_ID) REFERENCES ORGANIZING_COMMITTEE(COMMITTEE_ID)
);

-- ----------------------------------------------------------------
-- 2. Donor
