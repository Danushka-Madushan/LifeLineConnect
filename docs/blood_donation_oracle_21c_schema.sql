CREATE TABLE VENUE (
    VENUE_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COMMITTEE_ID         NUMBER NOT NULL,
    VENUE_NAME           VARCHAR2(200 CHAR) NOT NULL,
    ADDRESS              VARCHAR2(500 CHAR) NOT NULL,
    LATITUDE             NUMBER(9,6),
    LONGITUDE            NUMBER(9,6),
    CAPACITY             NUMBER(8) NOT NULL,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_VENUE PRIMARY KEY (VENUE_ID),
    CONSTRAINT CK_VENUE_CAPACITY CHECK (CAPACITY > 0),
    CONSTRAINT CK_VENUE_LAT CHECK (LATITUDE IS NULL OR LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_VENUE_LON CHECK (LONGITUDE IS NULL OR LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_VENUE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT FK_VENUE_COMMITTEE FOREIGN KEY (COMMITTEE_ID)
        REFERENCES ORGANIZING_COMMITTEE(COMMITTEE_ID)
);

CREATE TABLE DONATION_CAMP (
    CAMP_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COMMITTEE_ID         NUMBER NOT NULL,
    VENUE_ID             NUMBER NOT NULL,
    CAMP_TITLE           VARCHAR2(250 CHAR) NOT NULL,
    CAMP_DESCRIPTION     CLOB,
    CAMP_DATE            DATE NOT NULL,
    START_TIME           TIMESTAMP NOT NULL,
    END_TIME             TIMESTAMP NOT NULL,
    CAPACITY             NUMBER(8) NOT NULL,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    PUBLIC_VISIBLE       CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_DONATION_CAMP PRIMARY KEY (CAMP_ID),
    CONSTRAINT CK_CAMP_CAPACITY CHECK (CAPACITY > 0),
    CONSTRAINT CK_CAMP_TIME CHECK (END_TIME > START_TIME),
    CONSTRAINT CK_CAMP_STATUS CHECK (
        STATUS IN ('DRAFT', 'PUBLISHED', 'ONGOING', 'COMPLETED', 'CANCELLED', 'CLOSED')
    ),
    CONSTRAINT CK_CAMP_PUBLIC_VISIBLE CHECK (PUBLIC_VISIBLE IN ('Y', 'N')),
    CONSTRAINT FK_CAMP_COMMITTEE FOREIGN KEY (COMMITTEE_ID)
        REFERENCES ORGANIZING_COMMITTEE(COMMITTEE_ID),
    CONSTRAINT FK_CAMP_VENUE FOREIGN KEY (VENUE_ID)
        REFERENCES VENUE(VENUE_ID)
);

CREATE TABLE CAMP_TARGET_BLOOD_GROUP (
    CAMP_TARGET_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CAMP_ID              NUMBER NOT NULL,
    BLOOD_GROUP          VARCHAR2(3 CHAR) NOT NULL,

    CONSTRAINT PK_CAMP_TARGET_BLOOD_GROUP PRIMARY KEY (CAMP_TARGET_ID),
    CONSTRAINT UQ_CAMP_TARGET_BLOOD_GROUP UNIQUE (CAMP_ID, BLOOD_GROUP),
    CONSTRAINT CK_CAMP_TARGET_BLOOD_GROUP CHECK (
        BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    CONSTRAINT FK_CAMP_TARGET_CAMP FOREIGN KEY (CAMP_ID)
        REFERENCES DONATION_CAMP(CAMP_ID)
);

