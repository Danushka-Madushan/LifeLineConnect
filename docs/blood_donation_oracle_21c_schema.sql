CREATE TABLE HOSPITAL (
    HOSPITAL_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    HOSPITAL_CODE        VARCHAR2(40 CHAR) NOT NULL,
    HOSPITAL_NAME        VARCHAR2(250 CHAR) NOT NULL,
    CONTACT_PERSON       VARCHAR2(200 CHAR),
    PHONE                VARCHAR2(30 CHAR),
    EMAIL                VARCHAR2(255 CHAR),
    ADDRESS              VARCHAR2(500 CHAR),
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT PK_HOSPITAL PRIMARY KEY (HOSPITAL_ID),
    CONSTRAINT UQ_HOSPITAL_CODE UNIQUE (HOSPITAL_CODE),
    CONSTRAINT CK_HOSPITAL_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE HOSPITAL_BLOOD_REQUEST (
    REQUEST_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_CODE         VARCHAR2(40 CHAR) NOT NULL,
    HOSPITAL_ID          NUMBER NOT NULL,
    BLOOD_BANK_ID        NUMBER NOT NULL,
    BLOOD_GROUP          VARCHAR2(3 CHAR) NOT NULL,
    UNITS_REQUIRED       NUMBER(8,1) NOT NULL,
    UNITS_ALLOCATED      NUMBER(8,1) DEFAULT 0 NOT NULL,
    UNITS_FULFILLED      NUMBER(8,1) DEFAULT 0 NOT NULL,
    NEEDED_BY            TIMESTAMP WITH LOCAL TIME ZONE NOT NULL,
    PRIORITY             VARCHAR2(15 CHAR) DEFAULT 'NORMAL' NOT NULL,
    STATUS               VARCHAR2(25 CHAR) DEFAULT 'PENDING' NOT NULL,
    NOTES                CLOB,
    CREATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_HOSPITAL_BLOOD_REQUEST PRIMARY KEY (REQUEST_ID),
    CONSTRAINT UQ_HOSPITAL_REQUEST_CODE UNIQUE (REQUEST_CODE),
    CONSTRAINT CK_HOSPITAL_REQUEST_GROUP CHECK (
        BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')
    ),
    CONSTRAINT CK_HOSPITAL_REQUEST_UNITS CHECK (UNITS_REQUIRED > 0),
    CONSTRAINT CK_HOSPITAL_REQUEST_ALLOCATED CHECK (
        UNITS_ALLOCATED >= 0 AND UNITS_ALLOCATED <= UNITS_REQUIRED
    ),
    CONSTRAINT CK_HOSPITAL_REQUEST_FULFILLED CHECK (
        UNITS_FULFILLED >= 0 AND UNITS_FULFILLED <= UNITS_REQUIRED
        AND UNITS_FULFILLED <= UNITS_ALLOCATED
    ),
    CONSTRAINT CK_HOSPITAL_REQUEST_PRIORITY CHECK (
        PRIORITY IN ('LOW', 'NORMAL', 'HIGH', 'CRITICAL')
    ),
    CONSTRAINT CK_HOSPITAL_REQUEST_STATUS CHECK (
        STATUS IN ('PENDING', 'APPROVED', 'ALLOCATED', 'PARTIALLY_FULFILLED',
                   'FULFILLED', 'CANCELLED', 'CLOSED')
    ),
    CONSTRAINT FK_HOSPITAL_REQUEST_HOSPITAL FOREIGN KEY (HOSPITAL_ID)
        REFERENCES HOSPITAL(HOSPITAL_ID),
    CONSTRAINT FK_HOSPITAL_REQUEST_BANK FOREIGN KEY (BLOOD_BANK_ID)
        REFERENCES BLOOD_BANK(BLOOD_BANK_ID)
);

CREATE TABLE HOSPITAL_REQUEST_ALLOCATION (
    ALLOCATION_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_ID           NUMBER NOT NULL,
    BLOOD_UNIT_ID        NUMBER NOT NULL,
    ALLOCATED_AT         TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ISSUED_AT            TIMESTAMP WITH LOCAL TIME ZONE,
    STATUS               VARCHAR2(20 CHAR) DEFAULT 'RESERVED' NOT NULL,

    CONSTRAINT PK_HOSPITAL_REQUEST_ALLOCATION PRIMARY KEY (ALLOCATION_ID),
    CONSTRAINT UQ_HOSPITAL_REQUEST_UNIT UNIQUE (REQUEST_ID, BLOOD_UNIT_ID),
    CONSTRAINT CK_REQUEST_ALLOCATION_STATUS CHECK (
        STATUS IN ('RESERVED', 'ISSUED', 'CANCELLED')
    ),
    CONSTRAINT FK_REQUEST_ALLOC_REQUEST FOREIGN KEY (REQUEST_ID)
        REFERENCES HOSPITAL_BLOOD_REQUEST(REQUEST_ID),
    CONSTRAINT FK_REQUEST_ALLOC_UNIT FOREIGN KEY (BLOOD_UNIT_ID)
        REFERENCES BLOOD_UNIT(BLOOD_UNIT_ID)
);

